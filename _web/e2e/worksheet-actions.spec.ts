import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";
test("saved worksheets survive closing tabs, renaming, downloading and reload", async ({ page }) => {
 await page.emulateMedia({ colorScheme: "dark" });
 await page.goto("/");
 await page.getByLabel("Username", { exact: true }).fill("ADMIN");
 await page.getByLabel("Password", { exact: true }).fill("admin");
 await page.getByRole("button", { name: "Sign in", exact: true }).click();
 await page.locator(".cm-content").fill("SELECT 'saved worksheet' AS draft;");
 await page.locator('.wtab[aria-selected="true"]').hover();
 const actions = () => page.locator('.wtab[aria-selected="true"] .worksheet-menu-toggle');
 await actions().click();
 await page.getByRole("menuitem", { name: "Rename", exact: true }).click();
 await page.getByLabel("Worksheet name", { exact: true }).fill("Monthly report.sql");
 await page.getByLabel("Worksheet name", { exact: true }).press("Enter");
 await expect(page.locator('.wtab[aria-selected="true"] .wtab-name')).toHaveText("Monthly report.sql");
 await expect(page.locator(".worksheet-save-state")).toHaveText("Saved locally");
 await actions().click(); await page.getByRole("menuitem", { name: "Rename", exact: true }).click();
 await page.getByLabel("Worksheet name", { exact: true }).fill("Discard this rename");
 await page.getByLabel("Worksheet name", { exact: true }).press("Escape");
 await expect(page.locator('.wtab[aria-selected="true"] .wtab-name')).toHaveText("Monthly report.sql");
 await page.reload();
 await expect(page.locator(".cm-content")).toContainText("saved worksheet");
 await actions().click();
 await page.screenshot({ path: "/tmp/mallard-worksheet-actions.png" });
 const downloaded = page.waitForEvent("download");
 await page.getByRole("menuitem", { name: "Download", exact: true }).click();
 const file = await downloaded;
 expect(file.suggestedFilename()).toBe("Monthly report.sql");
 expect(await readFile((await file.path())!, "utf8")).toBe("SELECT 'saved worksheet' AS draft;");
 await page.getByRole("button", { name: "Close Monthly report.sql", exact: true }).click();
 await expect(page.locator(".wtab-name").filter({ hasText: "Monthly report.sql" })).toHaveCount(0);
 await page.locator('[data-sidebar="workspaces"]').click();
 await expect(page.locator(".worksheet-file").filter({ hasText: "Monthly report.sql" })).toBeVisible();
 await page.reload();
 await page.locator('[data-sidebar="workspaces"]').click();
 await page.locator(".worksheet-file").filter({ hasText: "Monthly report.sql" }).click();
 await expect(page.locator(".cm-content")).toContainText("saved worksheet");
 await actions().click(); await page.getByRole("menuitem", { name: "Delete", exact: true }).click();
 await page.getByRole("dialog").getByRole("button", { name: "Cancel", exact: true }).click();
 await expect(page.locator(".cm-content")).toContainText("saved worksheet");
 await actions().click(); await page.getByRole("menuitem", { name: "Delete", exact: true }).click();
 await page.getByRole("dialog").getByRole("button", { name: "Delete", exact: true }).click();
 await expect(page.locator(".worksheet-file").filter({ hasText: "Monthly report.sql" })).toHaveCount(0);
 await page.reload();
 await page.locator('[data-sidebar="workspaces"]').click();
 await expect(page.locator(".worksheet-file").filter({ hasText: "Monthly report.sql" })).toHaveCount(0);
});
