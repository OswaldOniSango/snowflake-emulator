-- Synthetic commerce demo. Run once as ADMIN / ACCOUNTADMIN.
-- Creates only MALLARD_DEMO_* objects. No DROP or OR REPLACE statements.
-- Run with run.mjs to configure the database, schema and warehouse context.

CREATE DATABASE MALLARD_DEMO_DB;
CREATE WAREHOUSE MALLARD_DEMO_WH WAREHOUSE_SIZE = 'X-SMALL' AUTO_RESUME = TRUE AUTO_SUSPEND = 300;
CREATE SCHEMA MALLARD_DEMO_DB.COMMERCE;
CREATE SCHEMA MALLARD_DEMO_DB.RAW;
CREATE SCHEMA MALLARD_DEMO_DB.OPERATIONS;

CREATE TABLE MALLARD_DEMO_DB.COMMERCE.CUSTOMERS (
  customer_id INTEGER, company VARCHAR, region VARCHAR, tier VARCHAR
);
CREATE TABLE MALLARD_DEMO_DB.COMMERCE.PRODUCTS (
  product_id INTEGER, product_name VARCHAR, category VARCHAR, unit_price DECIMAL(12,2)
);
CREATE TABLE MALLARD_DEMO_DB.COMMERCE.ORDERS (
  order_id INTEGER, customer_id INTEGER, ordered_at DATE, channel VARCHAR,
  status VARCHAR, gross_amount DECIMAL(12,2), discount_rate DOUBLE
);
CREATE TABLE MALLARD_DEMO_DB.COMMERCE.ORDER_ITEMS (
  order_id INTEGER, product_id INTEGER, quantity INTEGER, unit_price DECIMAL(12,2)
);
CREATE TABLE MALLARD_DEMO_DB.COMMERCE.PROCESSED_ORDERS (
  order_id INTEGER, customer_id INTEGER, ordered_at DATE, channel VARCHAR,
  status VARCHAR, gross_amount DECIMAL(12,2), discount_rate DOUBLE
);
CREATE TABLE MALLARD_DEMO_DB.COMMERCE.INVENTORY (
  product_id INTEGER, location VARCHAR, available_units INTEGER
);
CREATE TRANSIENT TABLE MALLARD_DEMO_DB.COMMERCE.PIPELINE_AUDIT (
  recorded_at TIMESTAMP, pipeline VARCHAR, status VARCHAR
);
CREATE TABLE MALLARD_DEMO_DB.RAW.LANDING_EVENTS (
  event_id INTEGER, event_type VARCHAR, payload VARCHAR
);
CREATE TABLE MALLARD_DEMO_DB.OPERATIONS.DATA_QUALITY_CHECKS (
  check_name VARCHAR, status VARCHAR, details VARCHAR
);

CREATE STAGE MALLARD_DEMO_DB.COMMERCE.ORDER_LANDING;
CREATE STAGE MALLARD_DEMO_DB.COMMERCE.PRODUCT_IMPORTS;
CREATE STAGE MALLARD_DEMO_DB.COMMERCE.PARTNER_EXPORTS;

CREATE FUNCTION MALLARD_DEMO_DB.COMMERCE.NET_REVENUE(amount DOUBLE, discount_rate DOUBLE)
RETURNS DOUBLE LANGUAGE SQL AS $$ ROUND(amount * (1 - discount_rate), 2) $$;
CREATE FUNCTION MALLARD_DEMO_DB.COMMERCE.ORDER_SEGMENT(amount DOUBLE)
RETURNS VARCHAR LANGUAGE SQL AS $$
  CASE WHEN amount >= 800 THEN 'Enterprise'
       WHEN amount >= 500 THEN 'Growth'
       ELSE 'Starter' END
$$;
CREATE FUNCTION MALLARD_DEMO_DB.COMMERCE.REVENUE_BAND(amount DOUBLE)
RETURNS VARCHAR LANGUAGE SQL AS $$
  CASE WHEN amount >= 1200 THEN 'HIGH' ELSE 'EMERGING' END
$$;

CREATE STREAM MALLARD_DEMO_DB.COMMERCE.ORDER_CHANGES
ON TABLE MALLARD_DEMO_DB.COMMERCE.ORDERS APPEND_ONLY = TRUE;
CREATE STREAM MALLARD_DEMO_DB.COMMERCE.INVENTORY_CHANGES
ON TABLE MALLARD_DEMO_DB.COMMERCE.INVENTORY APPEND_ONLY = TRUE;

