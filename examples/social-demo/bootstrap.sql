CREATE PROCEDURE MALLARD_DEMO_DB.COMMERCE.INGEST_ORDER_CHANGES()
RETURNS VARCHAR LANGUAGE SQL AS $$
BEGIN
  INSERT INTO MALLARD_DEMO_DB.COMMERCE.PROCESSED_ORDERS
  SELECT order_id, customer_id, ordered_at, channel, status, gross_amount, discount_rate
  FROM MALLARD_DEMO_DB.COMMERCE.ORDER_CHANGES;
  INSERT INTO MALLARD_DEMO_DB.COMMERCE.PIPELINE_AUDIT
  VALUES (CURRENT_TIMESTAMP, 'ORDER_INGESTION', 'SUCCESS');
  RETURN 'Orders processed';
END;
$$;
CREATE PROCEDURE MALLARD_DEMO_DB.COMMERCE.CHECK_PIPELINE_HEALTH()
RETURNS VARCHAR LANGUAGE SQL AS $$
BEGIN
  INSERT INTO MALLARD_DEMO_DB.OPERATIONS.DATA_QUALITY_CHECKS
  SELECT 'processed_order_count', 'PASS', CAST(COUNT(*) AS VARCHAR)
  FROM MALLARD_DEMO_DB.COMMERCE.PROCESSED_ORDERS;
  RETURN 'Quality checks recorded';
END;
$$;
CREATE PROCEDURE MALLARD_DEMO_DB.COMMERCE.RECORD_PIPELINE_HEARTBEAT()
RETURNS VARCHAR LANGUAGE SQL AS $$
BEGIN
  INSERT INTO MALLARD_DEMO_DB.COMMERCE.PIPELINE_AUDIT
  VALUES (CURRENT_TIMESTAMP, 'PIPELINE_HEARTBEAT', 'SUCCESS');
  RETURN 'Heartbeat recorded';
END;
$$;

-- Tasks remain suspended; EXECUTE TASK demonstrates real manual execution.
CREATE TASK MALLARD_DEMO_DB.COMMERCE.INGEST_ORDERS_TASK
WAREHOUSE = MALLARD_DEMO_WH SCHEDULE = '5 MINUTES'
AS CALL MALLARD_DEMO_DB.COMMERCE.INGEST_ORDER_CHANGES();
CREATE TASK MALLARD_DEMO_DB.COMMERCE.DATA_QUALITY_TASK
WAREHOUSE = MALLARD_DEMO_WH SCHEDULE = '15 MINUTES'
AS CALL MALLARD_DEMO_DB.COMMERCE.CHECK_PIPELINE_HEALTH();
CREATE TASK MALLARD_DEMO_DB.COMMERCE.PIPELINE_HEARTBEAT_TASK
WAREHOUSE = MALLARD_DEMO_WH SCHEDULE = '1 HOUR'
AS CALL MALLARD_DEMO_DB.COMMERCE.RECORD_PIPELINE_HEARTBEAT();
EXECUTE TASK MALLARD_DEMO_DB.COMMERCE.INGEST_ORDERS_TASK;
EXECUTE TASK MALLARD_DEMO_DB.COMMERCE.DATA_QUALITY_TASK;
EXECUTE TASK MALLARD_DEMO_DB.COMMERCE.PIPELINE_HEARTBEAT_TASK;

CREATE VIEW MALLARD_DEMO_DB.COMMERCE.ORDERS_ENRICHED AS
SELECT o.order_id, o.ordered_at, c.company, c.region, o.channel,
       o.gross_amount,
       NET_REVENUE(CAST(o.gross_amount AS DOUBLE), o.discount_rate) AS net_revenue,
       ORDER_SEGMENT(CAST(o.gross_amount AS DOUBLE)) AS segment
FROM MALLARD_DEMO_DB.COMMERCE.PROCESSED_ORDERS o
JOIN MALLARD_DEMO_DB.COMMERCE.CUSTOMERS c ON o.customer_id = c.customer_id;
CREATE VIEW MALLARD_DEMO_DB.COMMERCE.CUSTOMER_360 AS
SELECT c.company, c.region, c.tier, COUNT(o.order_id) AS orders,
       ROUND(SUM(o.net_revenue), 2) AS lifetime_revenue
FROM MALLARD_DEMO_DB.COMMERCE.CUSTOMERS c
JOIN MALLARD_DEMO_DB.COMMERCE.ORDERS_ENRICHED o ON c.company = o.company
GROUP BY c.company, c.region, c.tier;
CREATE VIEW MALLARD_DEMO_DB.COMMERCE.DAILY_REVENUE AS
SELECT ordered_at, COUNT(*) AS orders, ROUND(SUM(net_revenue), 2) AS revenue
FROM MALLARD_DEMO_DB.COMMERCE.ORDERS_ENRICHED GROUP BY ordered_at;
CREATE VIEW MALLARD_DEMO_DB.COMMERCE.PRODUCT_PERFORMANCE AS
SELECT p.product_name, p.category, SUM(i.quantity) AS units,
       SUM(i.quantity * i.unit_price) AS gross_revenue
FROM MALLARD_DEMO_DB.COMMERCE.ORDER_ITEMS i
JOIN MALLARD_DEMO_DB.COMMERCE.PRODUCTS p ON i.product_id = p.product_id
GROUP BY p.product_name, p.category;

-- TARGET_LAG is metadata in the current emulator; refresh is explicit.
CREATE DYNAMIC TABLE MALLARD_DEMO_DB.COMMERCE.REGIONAL_REVENUE
TARGET_LAG = '1 MINUTE' WAREHOUSE = MALLARD_DEMO_WH AS
SELECT region, COUNT(*) AS orders, COUNT(DISTINCT company) AS customers,
       ROUND(SUM(net_revenue), 2) AS revenue
FROM MALLARD_DEMO_DB.COMMERCE.ORDERS_ENRICHED GROUP BY region;
CREATE DYNAMIC TABLE MALLARD_DEMO_DB.COMMERCE.CHANNEL_PERFORMANCE
TARGET_LAG = '5 MINUTES' WAREHOUSE = MALLARD_DEMO_WH AS
SELECT channel, COUNT(*) AS orders, ROUND(SUM(net_revenue), 2) AS revenue
FROM MALLARD_DEMO_DB.COMMERCE.ORDERS_ENRICHED GROUP BY channel;
